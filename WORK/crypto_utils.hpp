/**
 * @file crypto_utils.hpp
 * @brief Lightweight AES‑256‑CBC and ChaCha20‑Poly1305 helpers.
 *
 * The implementation is intentionally small and depends only on the
 * OpenSSL library which is available on most CI runners.  All
 * functions are namespace‑local and do not throw; errors are
 * reported via return codes and simple exception handling.
 */

#pragma once

#include <openssl/evp.h>
#include <openssl/rand.h>
#include <vector>
#include <string>
#include <stdexcept>

/**
 * Holds ciphertext, tag and IV used for encryption.  For AES‑CBC
 * the tag is empty.
 */
struct CryptoResult {
    std::vector<unsigned char> ciphertext;
    std::vector<unsigned char> tag;   // empty for CBC
    std::vector<unsigned char> iv;
};

/**
 * Small utility wrapper around the OpenSSL EVP API.
 *
 * All functions use a 256‑bit key.  For CBC the IV is 16 bytes;
 * for ChaCha20‑Poly1305 the IV (nonce) is 12 bytes.
 */
class CryptoUtils {
public:
    /**
     * Encrypt a plaintext with AES‑256‑CBC.
     *
     * @param plaintext input text.
     * @param key 32‑byte key.
     * @param iv 16‑byte IV (generated by caller).
     * @return CryptoResult containing ciphertext and IV.
     */
    static CryptoResult encrypt_aes_256_cbc(
        const std::string &plaintext,
        const std::vector<unsigned char> &key,
        const std::vector<unsigned char> &iv);

    /**
     * Decrypt AES‑256‑CBC ciphertext.
     */
    static std::string decrypt_aes_256_cbc(
        const CryptoResult &res,
        const std::vector<unsigned char> &key);

    /**
     * Encrypt a plaintext with ChaCha20‑Poly1305.
     *
     * @param aad Additional authenticated data (optional, can be empty).
     */
    static CryptoResult encrypt_chacha20_poly1305(
        const std::string &plaintext,
        const std::vector<unsigned char> &key,
        const std::vector<unsigned char> &iv,
        const std::vector<unsigned char> &aad);

    /**
     * Decrypt ChaCha20‑Poly1305 ciphertext.
     */
    static std::string decrypt_chacha20_poly1305(
        const CryptoResult &res,
        const std::vector<unsigned char> &key,
        const std::vector<unsigned char> &aad);
};
